def get_category(product_name):

    product_name = str(product_name)


    # --------------------------------------------------------
    # 內衣
    # --------------------------------------------------------

    if (
        "內衣" in product_name
        or "BRA" in product_name.upper()
    ):
        return "內衣"


    # --------------------------------------------------------
    # POLO 衫
    # 必須放在 T恤 / 上衣之前判斷
    # --------------------------------------------------------

    elif (
        "POLO" in product_name.upper()
        or "Polo" in product_name
        or "polo" in product_name
    ):
        return "POLO衫"


    # --------------------------------------------------------
    # 襯衫
    # --------------------------------------------------------

    elif (
        "襯衫" in product_name
        or "法蘭絨襯衫" in product_name
    ):
        return "襯衫"


    # --------------------------------------------------------
    # 背心
    # --------------------------------------------------------

    elif (
        "背心" in product_name
        or "坦克背心" in product_name
        or "坦克" in product_name
    ):
        return "背心"


    # --------------------------------------------------------
    # 連帽上衣
    # --------------------------------------------------------

    elif (
        "連帽上衣" in product_name
        or "連帽休閒上衣" in product_name
    ):
        return "連帽上衣"


    # --------------------------------------------------------
    # 外套
    # --------------------------------------------------------

    elif (
        "外套" in product_name
        or "大衣" in product_name
        or "風衣" in product_name
        or "羽絨" in product_name
        or "夾克" in product_name
        or "茄克" in product_name
        or "開襟外套" in product_name
    ):
        return "外套"


    # --------------------------------------------------------
    # 針織
    # --------------------------------------------------------

    elif (
        "針織" in product_name
        or "毛衣" in product_name
    ):
        return "針織"


    # --------------------------------------------------------
    # 休閒上衣
    # --------------------------------------------------------

    elif (
        "休閒上衣" in product_name
        or "休閒衫" in product_name
        or "運動衫" in product_name
    ):
        return "休閒上衣"


    # --------------------------------------------------------
    # 褲子
    # --------------------------------------------------------

    elif (
        "長褲" in product_name
        or "短褲" in product_name
        or "牛仔褲" in product_name
        or "褲" in product_name
    ):
        return "褲子"


    # --------------------------------------------------------
    # T恤
    # --------------------------------------------------------

    elif (
        "T恤" in product_name
        or "Ｔ恤" in product_name
        or "T-shirt" in product_name
        or "T-Shirt" in product_name
        or "TEE" in product_name.upper()
    ):
        return "T恤"


    # --------------------------------------------------------
    # 上衣
    # --------------------------------------------------------

    elif "上衣" in product_name:
        return "上衣"


    # --------------------------------------------------------
    # 其他
    # --------------------------------------------------------

    else:
        return "其他"


df["category"] = (
    df["product_name"]
    .apply(get_category)
)


