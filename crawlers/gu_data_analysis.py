print("========================================")
print("男女裝價格統計表")
print("========================================")

gender_analysis = (
    df.groupby("gender")["price"]
    .agg(
        商品數量="count",
        平均價格="mean",
        最低價格="min",
        最高價格="max"
    )
    .round(2)
)

print(gender_analysis)


# ============================================================
