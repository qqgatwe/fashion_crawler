# ============================================================
# 11. 價格區間分類
# ============================================================

print()
print("========================================")
print("價格區間")
print("========================================")


def price_range(price):

    if price < 200:
        return "200元以下"

    elif price < 400:
        return "200-399元"

    elif price < 600:
        return "400-599元"

    elif price < 800:
        return "600-799元"

    elif price < 1000:
        return "800-999元"

    else:
        return "1000元以上"


df["price_range"] = df["price"].apply(
    price_range
)


# ============================================================
# 12. 統計各價格區間商品數量
# ============================================================

price_range_count = (
    df["price_range"]
    .value_counts()
)

# 讓價格區間按照我們設定的順序排列
price_order = [
    "200元以下",
    "200-399元",
    "400-599元",
    "600-799元",
    "800-999元",
    "1000元以上"
]

price_range_count = (
    price_range_count
    .reindex(price_order, fill_value=0)
)

print(price_range_count)


# ============================================================
# 13. 各價格商品數量
# ============================================================

print()
print("========================================")
print("各價格商品數量")
print("========================================")

price_count = (
    df["price"]
    .value_counts()
    .sort_index()
)

print(price_count)


# ============================================================
# 14. 找出最常見的商品價格
# ============================================================

print()
print("========================================")
print("最常見的商品價格")
print("========================================")

most_common_price = (
    df["price"]
    .value_counts()
    .idxmax()
)

most_common_count = (
    df["price"]
    .value_counts()
    .max()
)

print(
    f"最常見價格：{most_common_price} 元"
)

print(
    f"商品數量：{most_common_count} 件"
)


# ============================================================
# 15. 男女裝價格統計表
# ============================================================

